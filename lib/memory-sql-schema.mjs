// Native SQL storage format 1 mirrors the logical SQLite schema at version 6.
const SQL_SCHEMA_VERSION = "1";
const LOGICAL_SCHEMA_VERSION = "6";

function schemaMismatch() {
  return Object.assign(new Error("Memory database schema is not supported by this version."), { code: "schema_mismatch" });
}

async function createTables(driver, query, collation) {
  const mysql = driver === "mysql";
  const quote = (name) => mysql ? `\`${name}\`` : `"${name}"`;
  const key = quote("key");
  const reads = quote("reads");
  const trigger = quote("trigger");
  const text = mysql ? "LONGTEXT" : 'TEXT COLLATE "C"';
  // InnoDB uses a 3072-byte index key limit with its standard 16 KiB pages.
  const indexedText = (max) => mysql ? `VARCHAR(${max})` : text;
  const project = indexedText(255);
  const scope = indexedText(16);
  const status = indexedText(16);
  const taskId = indexedText(700);
  const hash = indexedText(64);
  const identity = mysql ? "BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY" : "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
  const digest = (value) => mysql ? `UNHEX(SHA2(${value}, 256))` : `agent_vault_sha256(${value})`;
  const tableOptions = mysql ? ` ENGINE=InnoDB ROW_FORMAT=DYNAMIC DEFAULT CHARACTER SET=utf8mb4 COLLATE=${collation}` : "";
  const create = (name, definition) => query(`CREATE TABLE IF NOT EXISTS ${name} (${definition})${tableOptions}`);

  if (!mysql) {
    // convert_to has general-purpose stable volatility. This wrapper always converts to UTF8.
    await query(`CREATE OR REPLACE FUNCTION agent_vault_sha256(value text) RETURNS bytea
      LANGUAGE sql IMMUTABLE STRICT AS $$
        SELECT pg_catalog.sha256(pg_catalog.convert_to(value, 'UTF8'))
      $$`);
    await query(`CREATE OR REPLACE FUNCTION agent_vault_review_action(value text) RETURNS text
      LANGUAGE plpgsql IMMUTABLE STRICT AS $$
        BEGIN
          RETURN value::json ->> 'action';
        EXCEPTION WHEN data_exception THEN
          RETURN NULL;
        END;
      $$`);
  }

  await create("meta", `
    k ${text} NOT NULL,
    v ${text} NOT NULL,
    k_sha256 ${mysql ? "BINARY(32)" : "BYTEA"} GENERATED ALWAYS AS (${digest("k")}) ${mysql ? "VIRTUAL" : "STORED"},
    CONSTRAINT meta_identity UNIQUE (k_sha256)
  `);
  await create("memories", `
    id ${identity},
    scope ${scope} NOT NULL CHECK (scope IN ('global', 'project', 'team')),
    project ${project},
    role ${indexedText(80)},
    team_id ${indexedText(128)} NOT NULL DEFAULT '',
    slug ${indexedText(255)},
    title ${text} NOT NULL,
    content ${text} NOT NULL,
    tags ${text} NOT NULL DEFAULT ('[]'),
    content_hash ${hash} NOT NULL,
    source_path ${text},
    status ${status} NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived', 'superseded')),
    superseded_by BIGINT,
    created_at ${text} NOT NULL,
    updated_at ${text} NOT NULL,
    last_read_at ${text},
    read_count BIGINT NOT NULL DEFAULT 0,
    kind ${indexedText(40)} NOT NULL DEFAULT 'knowledge',
    week_key ${indexedText(32)},
    event_date ${indexedText(32)},
    task_id ${text},
    worktree ${text}${mysql ? `,
    project_key ${project} GENERATED ALWAYS AS (COALESCE(project, '')) VIRTUAL,
    role_key ${indexedText(80)} GENERATED ALWAYS AS (COALESCE(role, '')) VIRTUAL,
    source_path_sha256 BINARY(32) GENERATED ALWAYS AS (${digest("source_path")}) VIRTUAL,
    INDEX memories_lookup (scope, project, role, status),
    INDEX memories_week (scope, project, week_key, event_date),
    INDEX memories_event_date (scope, project, event_date, kind),
    UNIQUE KEY memories_slug (scope, team_id, project_key, role_key, slug),
    UNIQUE KEY memories_source (team_id, source_path_sha256)` : ""}
  `);
  if (!mysql) {
    await query("CREATE INDEX IF NOT EXISTS memories_lookup ON memories (scope, project, role, status)");
    await query("CREATE INDEX IF NOT EXISTS memories_week ON memories (scope, project, week_key, event_date)");
    await query("CREATE INDEX IF NOT EXISTS memories_event_date ON memories (scope, project, event_date, kind)");
    await query(`CREATE UNIQUE INDEX IF NOT EXISTS memories_slug
      ON memories (scope, team_id, COALESCE(project, ''), COALESCE(role, ''), slug) WHERE slug IS NOT NULL`);
    await query(`CREATE UNIQUE INDEX IF NOT EXISTS memories_source
      ON memories (team_id, ${digest("source_path")}) WHERE source_path IS NOT NULL`);
  }
  await create("memory_embeddings", `
    memory_id BIGINT NOT NULL,
    model ${indexedText(700)} NOT NULL,
    dim INTEGER NOT NULL,
    vector ${mysql ? "LONGBLOB" : "BYTEA"} NOT NULL,
    text_hash ${hash} NOT NULL,
    created_at ${text} NOT NULL,
    PRIMARY KEY (memory_id, model),
    FOREIGN KEY (memory_id) REFERENCES memories(id)
  `);
  await create("activity", `
    ${key} ${indexedText(700)} PRIMARY KEY,
    ${reads} BIGINT NOT NULL DEFAULT 0,
    writes BIGINT NOT NULL DEFAULT 0,
    level BIGINT NOT NULL DEFAULT 0,
    last_op_at ${text}
  `);
  await create("reviews", `
    id ${identity},
    ${key} ${text} NOT NULL,
    reason ${text} NOT NULL,
    total_ops BIGINT NOT NULL,
    created_at ${text} NOT NULL,
    ready_at ${text},
    resolved_at ${text},
    resolution ${text}
  `);
  await create("memory_tasks", `
    id ${taskId} PRIMARY KEY,
    owner_pid INTEGER NOT NULL,
    status ${status} NOT NULL CHECK (status IN ('active', 'completed', 'cancelled')),
    started_at ${text} NOT NULL,
    finished_at ${text},
    owner_host ${text}
  `);
  await create("review_actions", `
    review_id BIGINT PRIMARY KEY,
    payload ${text} NOT NULL,
    status ${status} NOT NULL CHECK (status IN ('pending', 'applied', 'failed')),
    error_code ${text},
    created_at ${text} NOT NULL,
    updated_at ${text} NOT NULL,
    FOREIGN KEY (review_id) REFERENCES reviews(id)
  `);
  // Keep all bounded identity fields separate. Hash only the unbounded text, so no
  // delimiters, prefix lengths, or null sentinels can alias different composite keys.
  await create("review_feedback", `
    id ${identity},
    review_id BIGINT NOT NULL,
    memory_id BIGINT NOT NULL,
    ${trigger} ${indexedText(32)} NOT NULL CHECK (${trigger} IN ('user_correction', 'counterexample', 'external_evidence', 'outdated')),
    feedback ${text} NOT NULL,
    source_hash ${hash} NOT NULL,
    created_at ${text} NOT NULL,
    feedback_sha256 ${mysql ? "BINARY(32)" : "BYTEA"} GENERATED ALWAYS AS (${digest("feedback")}) ${mysql ? "VIRTUAL" : "STORED"},
    CONSTRAINT review_feedback_identity UNIQUE (review_id, memory_id, ${trigger}, feedback_sha256, source_hash),
    FOREIGN KEY (review_id) REFERENCES reviews(id),
    FOREIGN KEY (memory_id) REFERENCES memories(id)
  `);
  await create("weekly_task_attributions", `
    task_id ${taskId} PRIMARY KEY,
    week_key ${text} NOT NULL,
    business_date ${text} NOT NULL,
    time_zone ${text} NOT NULL,
    workday_start ${text} NOT NULL,
    parent_task_id ${taskId},
    resume_task_id ${taskId},
    FOREIGN KEY (task_id) REFERENCES memory_tasks(id),
    FOREIGN KEY (parent_task_id) REFERENCES memory_tasks(id),
    FOREIGN KEY (resume_task_id) REFERENCES memory_tasks(id)
  `);
  await create("weekly_exports", `
    path ${indexedText(700)} PRIMARY KEY,
    scope ${scope} NOT NULL CHECK (scope IN ('global', 'project')),
    project ${project},
    week_key ${text} NOT NULL,
    content_hash ${hash} NOT NULL,
    latest_event_date ${text} NOT NULL,
    exported_at ${text} NOT NULL
  `);
  await create("persona_profiles", `
    scope ${scope} NOT NULL CHECK (scope IN ('global', 'project')),
    project ${project} NOT NULL DEFAULT '',
    revision BIGINT NOT NULL DEFAULT 0,
    active ${text} NOT NULL DEFAULT ('[]'),
    applied_at ${text},
    PRIMARY KEY (scope, project)
  `);
  await create("persona_patterns", `
    id ${identity},
    scope ${scope} NOT NULL,
    project ${project} NOT NULL DEFAULT '',
    category ${indexedText(64)} NOT NULL,
    pattern ${indexedText(255)} NOT NULL,
    created_at ${text} NOT NULL,
    UNIQUE (scope, project, category, pattern),
    FOREIGN KEY (scope, project) REFERENCES persona_profiles(scope, project)
  `);
  await create("persona_evidence", `
    id ${identity},
    pattern_id BIGINT NOT NULL,
    guidance ${text} NOT NULL,
    source_kind ${indexedText(32)} NOT NULL CHECK (source_kind IN ('user_preference', 'observation')),
    evidence ${text} NOT NULL,
    evidence_hash ${hash} NOT NULL,
    task_id ${text},
    created_at ${text} NOT NULL,
    UNIQUE (pattern_id, evidence_hash),
    FOREIGN KEY (pattern_id) REFERENCES persona_patterns(id)${mysql ? ",\n    INDEX persona_evidence_pattern (pattern_id, id)" : ""}
  `);
  await create("persona_decisions", `
    id ${identity},
    pattern_id BIGINT NOT NULL,
    action ${indexedText(16)} NOT NULL CHECK (action IN ('accept', 'reject', 'disable')),
    guidance ${text},
    evidence_through BIGINT NOT NULL,
    applied_at ${text},
    created_at ${text} NOT NULL,
    FOREIGN KEY (pattern_id) REFERENCES persona_patterns(id)${mysql ? ",\n    INDEX persona_decisions_pattern (pattern_id, id)" : ""}
  `);
  if (!mysql) {
    await query("CREATE INDEX IF NOT EXISTS persona_evidence_pattern ON persona_evidence (pattern_id, id)");
    await query("CREATE INDEX IF NOT EXISTS persona_decisions_pattern ON persona_decisions (pattern_id, id)");
  }
}

const TRIGGERS = [
  ["review_feedback_no_update", "review_feedback", "UPDATE", "Review feedback is immutable."],
  ["review_feedback_no_delete", "review_feedback", "DELETE", "Review feedback is immutable."],
  ["persona_evidence_no_update", "persona_evidence", "UPDATE", "Persona evidence is immutable."],
  ["persona_evidence_no_delete", "persona_evidence", "DELETE", "Persona evidence is immutable."],
  ["persona_decisions_no_content_update", "persona_decisions", "UPDATE", "Persona decisions are immutable.",
    ["id", "pattern_id", "action", "guidance", "evidence_through", "created_at"]],
  ["persona_decisions_no_delete", "persona_decisions", "DELETE", "Persona decisions are immutable."],
];

async function createTriggers(driver, query, namespace) {
  const mysql = driver === "mysql";
  if (!mysql) {
    await query(`CREATE OR REPLACE FUNCTION agent_vault_reject_mutation() RETURNS trigger
      LANGUAGE plpgsql AS $$
        BEGIN
          RAISE EXCEPTION '%', TG_ARGV[0];
        END;
      $$`);
  }
  const { rows } = await query(`SELECT trigger_name AS name, event_object_table AS target
    FROM information_schema.triggers WHERE event_object_schema = ${namespace}
    AND event_object_table IN ('review_feedback', 'persona_evidence', 'persona_decisions')`);
  const installed = new Set(rows.map(({ name, target }) => `${target}.${name}`));
  for (const [name, table, event, message, columns] of TRIGGERS) {
    if (installed.has(`${table}.${name}`)) continue;
    if (mysql) {
      const reject = `SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '${message}'`;
      // MySQL has no UPDATE OF trigger. Compare the immutable fields null-safely.
      const action = columns ? `BEGIN
        IF NOT (${columns.map((column) => `OLD.${column} <=> NEW.${column}`).join(" AND ")}) THEN
          ${reject};
        END IF;
      END` : reject;
      await query(`CREATE TRIGGER ${name} BEFORE ${event} ON ${table} FOR EACH ROW ${action}`);
    } else {
      const of = columns ? ` OF ${columns.join(", ")}` : "";
      await query(`CREATE TRIGGER ${name} BEFORE ${event}${of} ON ${table}
        FOR EACH ROW EXECUTE FUNCTION agent_vault_reject_mutation('${message}')`);
    }
  }
}

// The caller holds the migration lock for this connection. On MySQL-family servers
// each DDL statement can commit independently; both version stamps come last.
export async function initializeSqlSchema(driver, query, purpose) {
  if (driver !== "mysql" && driver !== "postgres") throw new TypeError("Unsupported SQL database driver.");
  const mysql = driver === "mysql";
  const namespace = mysql ? "DATABASE()" : "current_schema()";
  const { rows: [meta] } = await query(`SELECT table_type AS relation_type
    FROM information_schema.tables WHERE table_schema = ${namespace} AND table_name = 'meta'`);

  const keys = ["schema", "sql_schema", "database_scope"];
  if (meta) {
    if (meta.relation_type !== "BASE TABLE") throw schemaMismatch();
    const lookup = keys.map((key) => mysql ? `UNHEX(SHA2('${key}', 256))` : `agent_vault_sha256('${key}')`).join(", ");
    const { rows } = await query(`SELECT k, v FROM meta WHERE k_sha256 IN (${lookup})`);
    const versions = new Map(rows.map(({ k, v }) => [k, v]));
    if (versions.size) {
      if (versions.get("schema") !== LOGICAL_SCHEMA_VERSION || versions.get("sql_schema") !== SQL_SCHEMA_VERSION) throw schemaMismatch();
      if (versions.get("database_scope") !== purpose) throw Object.assign(new Error(), { code: "database_scope_mismatch" });
      return;
    }
  } else {
    const { rows } = await query(`SELECT 1 FROM information_schema.tables WHERE table_schema = ${namespace} LIMIT 1`);
    if (rows.length) throw schemaMismatch();
  }

  let collation;
  if (mysql) {
    const { rows: [server] } = await query("SELECT VERSION() AS server_version, @@version_comment AS version_comment");
    collation = /mariadb/i.test(`${server.server_version} ${server.version_comment}`) ? "utf8mb4_nopad_bin" : "utf8mb4_0900_bin";
  } else {
    const { rows: [server] } = await query("SHOW server_encoding");
    if (server.server_encoding !== "UTF8") throw schemaMismatch();
  }
  await createTables(driver, query, collation);
  await createTriggers(driver, query, namespace);

  const stamps = [["schema", LOGICAL_SCHEMA_VERSION], ["sql_schema", SQL_SCHEMA_VERSION], ["database_scope", purpose]];
  const values = stamps.map((_, i) => mysql ? "(?, ?)" : `($${2 * i + 1}, $${2 * i + 2})`).join(", ");
  await query(`INSERT INTO meta (k, v) VALUES ${values}`, stamps.flat());
}
